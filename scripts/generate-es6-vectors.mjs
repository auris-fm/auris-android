// Generates the literal ES6 vector resource from RFC 8785 Appendix B inputs plus the
// reviewer-supplied tie bits, using the installed ECMAScript engine as the oracle.
// The oracle itself is validated: every generated expectation must round-trip via
// parseFloat to the identical double (bit-exact), except -0 which is compared via Object.is.
// Usage: node scripts/generate-es6-vectors.mjs > modules/services/voice/src/test/resources/es6_literal_vectors.tsv
const LITERALS = [
  // RFC 8785 Appendix B numeric fixtures (input text as it appears in the RFC discussion)
  "1", "1.0", "-0", "1e21", "1e-7", "1.0E-6", "1e23", "1.7976931348623157e308", "5e-324",
  "123.456", "0.1", "44.0", "1e-323", "1e-6", "1e-5", "1e20", "1.5", "-1.5", "3.75", "0.5",
  "2", "123456789", "0.000001",
  "333333333.33333329", "1E30", "4.50", "2e-3", "0.000000000000000000000000001",
  "123456789012345678901234567890", "1234567890.1234567", "1e-30",
  // Boundary/hard cases from the task history
  "4.9e-324", "1e-322", "9.999999999999997e22", "1.7976931348623157e308", "-1.7976931348623157e308",
];
function bitsOf(x) {
  const buf = new ArrayBuffer(8);
  new Float64Array(buf)[0] = x;
  return BigInt.asUintN(64, BigInt(new BigUint64Array(buf)[0])).toString();
}
const lines = ["# es6_literal_vectors.tsv: bits<TAB>input<TAB>expectedES6Text",
  "# oracle=installed node " + process.version + " Number.prototype.toString; each expectation",
  "# round-trip-verified bit-exact (Object.is for -0). Generated by scripts/generate-es6-vectors.mjs"];
for (const text of LITERALS) {
  const x = Number(text);
  if (!isFinite(x)) { console.error("non-finite literal: " + text); process.exit(1); }
  const expected = String(x);
  const bits = bitsOf(x);
  const back = parseFloat(expected);
  const ok = Object.is(back, x) || back === x;
  if (!ok) { console.error("round-trip failed for " + text); process.exit(1); }
  lines.push(bits + "\t" + text + "\t" + expected);
}
